# Loops are and essential part of programming. They allow you to repeat a block of code multiple times.
#There are two types of loops in python, "for" and "while"

#"for" loop
# the "for" loop is used to iterate over a sequence (list, tuple, string) or other iterable objects.
#Let us iterate over list
fruits = ("apple", "banana","cherry", "pineapple")

for fruit in fruits:
    print(fruit)

for i in range(10):
    print(1)

for i in range (7):
    print(i)

for char in "Jacinta":
    print(char)